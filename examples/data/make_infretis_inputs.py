RUNNER = """#!/usr/bin/env bash
# StapleTIS run (infinite swap, ASE overdamped Langevin). Needs the APPTIS checkouts of ASE (OverdampedLangevin),
# infretis (StapleTIS) and inftools in front of the installed packages, and the toytis checkout for ToytisPotential.
APPTIS=${APPTIS:-/mnt/0bf0c339-34bb-4500-a5fb-f3c2a863de29/DATA/APPTIS}
export TOYTIS=${TOYTIS:-/mnt/0bf0c339-34bb-4500-a5fb-f3c2a863de29/DATA/PyRETIS3/toytis}
export PYTHONPATH=$APPTIS/ase:$APPTIS/infretis:$APPTIS/inftools:$PWD:$PYTHONPATH
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
bash clean.sh
cp -r load_copy load
infretisrun -i infretis.toml
"""
CLEAN = "rm -rf worker* infretis_data*.txt sim.log restart.toml load pattern.txt infretis.out\n"


def build(name, spec):
    out = os.path.join(OUT, name)
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    with open(spec["toml"], "rb") as f:
        cfg = tomllib.load(f)
    n_int = len(cfg["simulation"]["interfaces"])
    seeds = sorted(os.listdir(spec["seeds"]), key=int)
    if len(seeds) != n_int:
        raise ValueError(f"{name}: {len(seeds)} seed paths for {n_int} interfaces")
    for key in ("current", "infinit"):
        cfg.pop(key, None)
    cfg["orderparameter"]["module"] = "./infretis_orderp.py"
    cfg["engine"]["calculator_settings"]["module"] = "./ase_calcs.py"
    cfg["output"]["delete_old"] = False
    cfg["output"]["delete_old_all"] = False
    with open(os.path.join(out, "infretis.toml"), "wb") as f:
        tomli_w.dump(cfg, f)
    for src in (f"{PL}/loop/ase_calcs.py", f"{PL}/infretis_orderp.py", f"{PL}/lambda_runtime.py"):
        shutil.copy(src, out)
    for s in seeds:
        shutil.copytree(os.path.join(spec["seeds"], s), os.path.join(out, "load_copy", s))
    with open(os.path.join(out, "runner.sh"), "w") as f:
        f.write(RUNNER)
    with open(os.path.join(out, "clean.sh"), "w") as f:
        f.write(CLEAN)
    os.chmod(os.path.join(out, "runner.sh"), 0o755)
    e, sim = cfg["engine"], cfg["simulation"]
    with open(os.path.join(out, "README.md"), "w") as f:
        f.write(f"""# {spec['title']}: infretis StapleTIS input

{spec['text']}

| | |
|---|---|
| sampler | infretis `mode = "staple"`, `staple_infinite_swap = {sim['staple_infinite_swap']}`, {cfg['runner']['workers']} workers, `steps = {sim['steps']}` cycles |
| engine | ASE `{e['integrator']}`, timestep {e['timestep']:.6g} fs, friction {e['langevin_friction']:.6g} / fs, T = {e['temperature']:.6g} K (reduced units: sigma = 1 A, epsilon = 1 eV, m = 1 amu, time unit 10.18 fs) |
| interfaces | {sim['interfaces']} |
| toytis run | {spec['toytis']} |
| initial paths | `load_copy/0..{n_int - 1}`: one valid staple path per ensemble (copied from the order-parameter loop: {os.path.relpath(spec['seeds'], EXAMPLES)}) |

Start: `bash runner.sh` (cleans, copies `load_copy` to `load`, runs `infretisrun -i infretis.toml`). The paths of the
checkouts are set in `runner.sh`; `ToytisPotential` loads the potential from the toytis checkout (`$TOYTIS`).
`delete_old = false`: every accepted path is kept in `load/`.

Analysis: `python examples/load_tis_data_cupy.py <this folder> --reversed --h5 ...` or `examples/infretis_staple_1d.ipynb`
(`tis_data.prepare_data` reads infretis runs; weights and the cut at M: `docs/npneq_tis_notes.md` section 15; the loop's
choice of weights: `docs/op_loop_report.md`). Rates: `inftools.istar`.

The ASE overdamped integrator makes the same step as toytis' Brownian engine, x += dt F / (m gamma) + N(0, 2 kT dt / (m gamma)),
so the exact committors of the discrete toytis chains apply.
""")
    return out


