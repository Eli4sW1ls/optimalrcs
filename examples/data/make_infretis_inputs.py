"""Self-contained infretis StapleTIS input folders for the toy systems of the toytis staple runs, in data/infretis_inputs/.

    python make_infretis_inputs.py

Nothing is generated by MD here: every folder is assembled from files that already exist in the order-parameter loop
(figures_by_potential/_shared/param_lambda/op_loop/):
  * infretis.toml  = the toml of the loop's seed-lambda production run (mode staple, infinite swap, ASE engine, overdamped
                     Langevin, positional order parameter), with the module paths made relative to the run folder;
  * load_copy/     = its seed paths (one valid staple path per ensemble: order.txt, traj.txt, accepted/*.traj);
  * ase_calcs.py, infretis_orderp.py, lambda_runtime.py = the calculators and the order-parameter module of
                     examples/param_lambda (copied, so the folder runs on its own);
  * runner.sh, clean.sh, README.md.
"""
